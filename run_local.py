import json
import urllib.request

# Настройки локального сервера Ollama
url = "http://localhost:11434/api/generate"

# Исправленный запрос для Вопроса 3 с физически корректным базисом
prompt = """
Контекст нашего проекта (квантово-тернарный процессор на сфиральной топологии):
1. Базис: ортонормированный |L>, |S>, |R> в C³.
2. Канонический оператор U_S(1) фиксирован матрицей инверсии хиральности.

Вопрос 3 (Исправление измерения и тернарной проекции из C³ в {-1, 0, +1}):
Как корректно реализовать измерение квантового кутрита |ψ⟩ = α_L|L⟩ + α_S|S⟩ + α_R|R⟩ в сбалансированное троичное пространство {-1, 0, +1}?
Нужно учесть:
1. Вероятности Борна для коллапса: P(L) = |α_L|², P(S) = |α_S|², P(R) = |α_R|².
2. Оператор наблюдаемой (троичного заряда) Q = (+1)*|R><R| + (0)*|S><S| + (-1)*|L><L| или пороговое сканирование.
3. Напиши чистый и правильный класс на Python для симулятора этого измерения (без деления на ноль и вырожденных матриц).
"""

data = {
    "model": "deepseek-coder:1.3b",
    "prompt": prompt,
    "stream": False
}

req = urllib.request.Request(
    url, 
    data=json.dumps(data).encode('utf-8'), 
    headers={'Content-Type': 'application/json'}
)

print("Отправка исправленного запроса локальной модели DeepSeek-Coder (1.3b)...")

try:
    with urllib.request.urlopen(req) as response:
        result = json.loads(response.read().decode('utf-8'))
        print("\n=== ОТВЕТ ЛОКАЛЬНОЙ МОДЕЛИ (ИЗМЕРЕНИЕ) ===")
        print(result.get("response", "Нет ответа"))
except Exception as e:
    print(f"Ошибка соединения с Ollama: {e}")